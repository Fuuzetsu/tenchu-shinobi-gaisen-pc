import assert from 'node:assert/strict';
import {pathToFileURL} from 'node:url';
import {mkdir, readFile} from 'node:fs/promises';
import {sceneImage} from './browser-image.mjs';
import {installAudioProbe} from './browser-audio.mjs';
const {chromium} = await import(pathToFileURL(process.env.PLAYWRIGHT_MODULE).href);
const output = process.env.TENCHU_WEB_CAPTURES ?? 'private/browser-trial';
const base = process.env.TENCHU_WEB_URL ?? 'http://127.0.0.1:8000';
const errors = [];
await mkdir(output, {recursive:true});
const browser = await chromium.launch({headless:process.env.TENCHU_HEADLESS==='1',executablePath:process.env.BROWSER_EXECUTABLE,args:['--no-sandbox','--mute-audio','--enable-unsafe-webgpu','--ignore-gpu-blocklist','--ozone-platform=x11','--use-angle=vulkan','--enable-features=Vulkan,VulkanFromANGLE','--disable-vulkan-surface']});
const context = await browser.newContext({viewport:{width:1280,height:800},acceptDownloads:true});
await context.addInitScript(artwork => localStorage.setItem('tenchu-pc/settings.json',JSON.stringify(Array.from(new TextEncoder().encode(JSON.stringify({pause_on_defocus:false,graphics:{asset_pack:artwork,lighting:{enabled:artwork}}}))))),process.env.TENCHU_HD_ARTWORK==='1');
await context.addInitScript(installAudioProbe);
const page = await context.newPage();
page.on('pageerror',e=>{errors.push(e.stack);console.error(e.stack);});
page.on('console',m=>{if(m.type()==='error' || /GL_INVALID_|WebGL: INVALID_/.test(m.text())) {errors.push(m.text());console.error(m.text());}});
const key=async k=>{await page.keyboard.press(k);await page.waitForTimeout(600);};
const shot=async(name,scene=false)=>{
 const png=await page.screenshot({path:`${output}/${name}.png`});
 if(scene) assert((await page.evaluate(sceneImage,png.toString('base64'))).colors>64,'Trial scene must render');
};
const state=()=>page.evaluate(()=>JSON.parse(window.port.snapshot()));
try {
 await page.goto(`${base}/?renderer=${process.env.TENCHU_WEBGL==='1'?'webgl2':'webgpu'}`);
 await page.click('#play');
 await page.waitForFunction(()=>document.body.dataset.ready==='true',null,{timeout:60000});
 await page.waitForFunction(()=>document.body.dataset.assetsReady==='true',null,{timeout:120000});
 await page.evaluate(async()=>{window.port=await import('./pkg/tenchu_pc.js');});
 await key('Enter');await key('F10');await page.waitForTimeout(6000);await key('F10');
 await page.mouse.click(795,237);await page.keyboard.press('Control+a');await page.keyboard.insertText('忍者');await page.mouse.click(1200,700);
 await shot('library');
 await page.mouse.click(222,18);await page.waitForTimeout(1500);
 const preview=await state();
 assert(preview.paused && preview.screen==='playing','3D preview must pause gameplay');
 await page.keyboard.down('Shift');await page.keyboard.down('w');await page.waitForTimeout(120);
 await page.keyboard.up('w');await page.keyboard.up('Shift');
 assert.deepEqual(await state(),preview,'Preview boost must neither cancel nor advance gameplay');
 await shot('preview-boost',true);
 await key('Escape');await key('Escape');
 await key('F5');await page.waitForTimeout(5000);console.log('PLAY',await state());
 assert((await state()).trial,'Must enter trial gameplay');
 await page.keyboard.down('w');await page.waitForTimeout(1500);await key('Space');await page.keyboard.up('w');
 await key('z');await key('e');await key('j');await shot('gameplay',true);
 assert(await page.evaluate(()=>window.audioProbe.nonSilent),'Trial audio must play');
 await key('Escape');
 const click=async(x,y)=>{await page.mouse.click(x,y);await page.waitForTimeout(500);};
 await click(90,38);await shot('terrain');
 await click(32,38);await click(338,108);await shot('new-map');
 await click(754,194);await click(211,302);
 await click(385,18);await shot('saved');
 const saved = await page.evaluate(()=>JSON.parse(new TextDecoder().decode(new Uint8Array(JSON.parse(localStorage.getItem('tenchu-pc/trials.json'))))));
 assert.equal(saved.missions.length,1,'Save creates local library entry');
 assert.equal(new TextDecoder('shift-jis').decode(new Uint8Array(saved.missions[0].slice(8,19))),'New mission');
 assert(saved.missions[0].slice(236,2284).filter((v,i)=>i%2===0&&v===1).length>0,'Mouse painting must change terrain');
 await key('F5');await page.waitForTimeout(1200);assert.equal((await state()).trial.title,'New mission');
 await key('Escape');await click(322,38);await shot('share');
 const downloading=page.waitForEvent('download');
 await click(133,124);
 const filename=`${output}/mission.msn`;
 await (await downloading).saveAs(filename);
 assert.deepEqual(Array.from(await readFile(filename)),saved.missions[0]);
 const choosing=page.waitForEvent('filechooser');
 await click(42,124);
 await (await choosing).setFiles(filename);
 await page.waitForTimeout(1000);
 await key('F5');assert.equal((await state()).trial.title,'New mission');
 assert.equal((await state()).fault,'');
 await key('Escape');
 assert.deepEqual(errors,[]);
 await key('Escape');await page.waitForTimeout(1000);assert.equal((await state()).trial,null);console.log('RETURN',await state());
} finally {await browser.close();}
